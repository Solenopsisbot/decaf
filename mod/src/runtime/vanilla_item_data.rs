//! Vanilla Minecraft 26.3 item metadata captured from Java 25 on the 26.3 server:
//! registered item ids, non-64 max stack sizes, vanilla item tags, and
//! `DataComponents` field ids. Contains only registry/tag identifiers and integers.

/// Whether `id` is a vanilla 26.3 registered item (`BuiltInRegistries.ITEM`).
pub(crate) fn is_vanilla_item(id: &str) -> bool {
    VANILLA_ITEMS.binary_search(&id).is_ok()
}

/// Exact vanilla 26.3 default max stack size for a vanilla item id.
pub(crate) fn vanilla_max_stack_size(id: &str) -> Option<i32> {
    if !is_vanilla_item(id) {
        return None;
    }
    if let Ok(index) = NON_64_MAX_STACK.binary_search_by(|(k, _)| k.cmp(&id)) {
        return Some(i32::from(NON_64_MAX_STACK[index].1));
    }
    Some(64)
}

/// Exact vanilla 26.3 prototype `DataComponents.MAX_DAMAGE` for a vanilla item id.
/// Returns `None` if `id` is not a vanilla item, `Some(None)` if non-damageable, or
/// `Some(Some(max_damage))` if damageable.
pub(crate) fn vanilla_max_damage(id: &str) -> Option<Option<i32>> {
    if !is_vanilla_item(id) {
        return None;
    }
    match VANILLA_MAX_DAMAGE.binary_search_by(|(k, _)| k.cmp(&id)) {
        Ok(index) => Some(Some(VANILLA_MAX_DAMAGE[index].1)),
        Err(_) => Some(None),
    }
}

/// Whether `id` is a vanilla 26.3 `BuiltInRegistries.RECIPE_SERIALIZER` id.
pub(crate) fn is_vanilla_recipe_serializer(id: &str) -> bool {
    VANILLA_RECIPE_SERIALIZERS.binary_search(&id).is_ok()
}

/// Whether `id` is a vanilla 26.3 `BuiltInRegistries.RECIPE_TYPE` id.
pub(crate) fn is_vanilla_recipe_type(id: &str) -> bool {
    VANILLA_RECIPE_TYPES.binary_search(&id).is_ok()
}

/// Raw entry list for a vanilla 26.3 `minecraft:*` item tag.
pub(crate) fn vanilla_item_tag(tag_id: &str) -> Option<&'static [&'static str]> {
    VANILLA_ITEM_TAGS
        .binary_search_by(|(k, _)| k.cmp(&tag_id))
        .ok()
        .map(|index| VANILLA_ITEM_TAGS[index].1)
}

/// Registry id for `DataComponents.<field>`, or `None` when 26.3 lacks it.
pub(crate) fn data_component_field_id(field: &str) -> Option<&'static str> {
    DATA_COMPONENT_FIELDS
        .binary_search_by(|(k, _)| k.cmp(&field))
        .ok()
        .map(|index| DATA_COMPONENT_FIELDS[index].1)
}

/// Every vanilla 26.3 `DataComponents` registry id (`minecraft:*`).
pub fn all_vanilla_data_component_ids() -> impl Iterator<Item = &'static str> {
    DATA_COMPONENT_FIELDS.iter().map(|(_, id)| *id)
}

/// `Item.canFitInsideContainerItems()` of a vanilla 26.3 item, `None` for an id that isn't one.
///
/// 26.3's `Item` answers `true` (`iconst_1; ireturn`) and `BlockItem` answers
/// `!(getBlock() instanceof ShulkerBoxBlock)`; no other class of the server jar declares it.
/// The items answering `false` ([`CANNOT_FIT_INSIDE_CONTAINER_ITEMS`]) were captured on Java 25
/// by calling it on every `BuiltInRegistries.ITEM` entry after `Bootstrap.bootStrap()`
/// (`vanilla_can_fit_inside_container_items_java25.txt`, from the oracle in
/// `tests/fixtures/vanilla_can_fit_inside_container_items/`).
pub(crate) fn vanilla_can_fit_inside_container_items(id: &str) -> Option<bool> {
    if !is_vanilla_item(id) {
        return None;
    }
    Some(
        CANNOT_FIT_INSIDE_CONTAINER_ITEMS
            .binary_search(&id)
            .is_err(),
    )
}

