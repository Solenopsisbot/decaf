#!/usr/bin/env python3
"""Record the order in which the 26.3 server's bootstrap finishes each game class's `<clinit>`.

Writes `crates/horizon-native-java/src/bootstrap_clinit_order_26_3.txt`: the internal names of
every class of the Minecraft server jar whose static initializer returns while the server's
`Main.main` prelude runs (`SharedConstants.tryDetectVersion()`, `CrashReport.preload()`,
`Bootstrap.bootStrap()`, the calls `net.minecraft.server.Main.main` makes before anything reads
its options), one per line, in the order those initializers return.

Why the runtime needs it
------------------------
A Mixin `@Inject(method = "<clinit>", at = @At("TAIL"))` into a game class runs once, as the last
thing that class's static initializer does. Bundle API registers its data component type that way
(`DataComponentTypesMixin` into `DataComponents`, `Registry.register(BuiltInRegistries
.DATA_COMPONENT_TYPE, ...)`). The runtime models game classes on the host, so their initializers
never run there; it runs such callbacks itself before a jar's first entrypoint
(`bootstrap_mixins.rs`). When callbacks target several game classes, they run in the order those
classes finish initializing on a real server, which is this list: a `TAIL` injector runs at its
class's *completion*, and one class's initializer can start another's, so the JVM's
`-Xlog:class+init` (which logs starts only) can't give it.

How it is measured
------------------
A Java agent (`InitEndAgent`, JDK 25's `java.lang.classfile`) rewrites every `net/minecraft/`
class's `<clinit>` so that each `return` first calls `InitEnd.done("<class>")`, which appends
the name to a queue; a `main` mirroring `Main.main`'s prelude runs it and prints the queue. An
initializer that throws never returns and is not listed. The prelude has no inputs (no world, no
options), so the list is the same on every run. Fabric does not change it: it loads game classes
through Knot and Mixin's transformer, but initializes them in the game's order, and runs `main`
entrypoints only after this bootstrap (`fabric_server_bootstrap_classes_26_3.txt` lists
`DataComponents` among the classes a real Fabric server loads before the first entrypoint).

Reproducing the committed file byte-for-byte
--------------------------------------------
    python3 tools/trace_bootstrap_clinit_order.py \\
        --server-jar <unbundled Minecraft 26.3 server jar> \\
        --libs <the bundle's META-INF/libraries directory> \\
        --jdk <JDK 25 home, e.g. Temurin 25.0.5+8> \\
        --output crates/horizon-native-java/src/bootstrap_clinit_order_26_3.txt

The server jar's `version.json` must name 26.3 and the JDK must be 25; the server jar's SHA-256
and the JDK's `java.runtime.version` are recorded as `# input` lines and checked on every later
run (`--record` writes new ones, for a deliberate change of inputs).
"""

from __future__ import annotations

import argparse
import hashlib
import json
import subprocess
import sys
import tempfile
import zipfile
from pathlib import Path

GAME_VERSION = "26.3"
JDK_FEATURE = "25"

HEADER = """\
# Game classes whose <clinit> returns during the 26.3 server's bootstrap, in the order they return.
# Minecraft 26.3 server, JDK 25: SharedConstants.tryDetectVersion(), CrashReport.preload(),
# Bootstrap.bootStrap() (net.minecraft.server.Main.main's prelude). Generated by
# tools/trace_bootstrap_clinit_order.py (a java.lang.classfile agent); do not edit by hand. The
# `# input` lines are the exact inputs, which the tool checks before every run. Then one internal
# class name per line, in completion order.
"""

AGENT_SOURCE = """\
import java.lang.classfile.*;
import java.lang.classfile.instruction.ReturnInstruction;
import java.lang.constant.ClassDesc;
import java.lang.constant.MethodTypeDesc;
import java.lang.instrument.ClassFileTransformer;
import java.lang.instrument.Instrumentation;
import java.security.ProtectionDomain;

/** Calls `InitEnd.done("<class>")` before every return of each net/minecraft `<clinit>`. */
public class InitEndAgent {
    public static void premain(String args, Instrumentation inst) {
        inst.addTransformer(new ClassFileTransformer() {
            @Override
            public byte[] transform(ClassLoader loader, String name, Class<?> redefined,
                                    ProtectionDomain domain, byte[] bytes) {
                if (name == null || !name.startsWith("net/minecraft/")) return null;
                try {
                    ClassFile cf = ClassFile.of(ClassFile.ClassHierarchyResolverOption.of(
                        ClassHierarchyResolver.defaultResolver().orElse(
                            ClassHierarchyResolver.ofResourceParsing(loader))));
                    ClassModel model = cf.parse(bytes);
                    if (model.methods().stream().noneMatch(m -> m.methodName().equalsString("<clinit>"))) {
                        return null;
                    }
                    return cf.transformClass(model, ClassTransform.transformingMethodBodies(
                        m -> m.methodName().equalsString("<clinit>"),
                        (builder, element) -> {
                            if (element instanceof ReturnInstruction) {
                                builder.ldc(name);
                                builder.invokestatic(ClassDesc.of("InitEnd"), "done",
                                    MethodTypeDesc.ofDescriptor("(Ljava/lang/String;)V"));
                            }
                            builder.with(element);
                        }));
                } catch (Throwable t) {
                    System.err.println("INITEND-TRANSFORM-FAILED " + name + " " + t);
                    return null;
                }
            }
        });
    }
}
"""

INIT_END_SOURCE = """\
import java.util.concurrent.ConcurrentLinkedQueue;

public final class InitEnd {
    static final ConcurrentLinkedQueue<String> DONE = new ConcurrentLinkedQueue<>();
    public static void done(String name) { DONE.add(name); }
}
"""

BOOT_SOURCE = """\
public class Boot {
    public static void main(String[] args) throws Exception {
        net.minecraft.SharedConstants.tryDetectVersion();
        net.minecraft.CrashReport.preload();
        net.minecraft.server.Bootstrap.bootStrap();
        // The game replaces System.out with its logger; write the list to the file named.
        java.nio.file.Files.write(java.nio.file.Path.of(args[0]), InitEnd.DONE);
    }
}
"""


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


def jdk_runtime_version(jdk: Path) -> str:
    """`java.runtime.version` of the JDK at `jdk`."""
    result = subprocess.run(
        [str(jdk / "bin" / "java"), "-XshowSettings:properties", "-version"],
        capture_output=True,
        text=True,
        check=True,
    )
    for line in result.stderr.splitlines():
        key, _, value = line.strip().partition(" = ")
        if key == "java.runtime.version":
            return value
    raise SystemExit(f"no java.runtime.version from {jdk}")


def input_manifest(server_jar: Path, jdk: Path) -> list[str]:
    """The trace's inputs as `# input` header lines, after checking the versions."""
    with zipfile.ZipFile(server_jar) as archive:
        if "META-INF/versions.list" in archive.namelist():
            raise SystemExit(f"{server_jar.name} is the server bundler; pass the server jar it unpacks")
        try:
            version = json.loads(archive.read("version.json"))["id"]
        except KeyError:
            raise SystemExit(f"{server_jar.name} has no version.json: not an unbundled server jar")
    if version != GAME_VERSION:
        raise SystemExit(f"{server_jar.name} is Minecraft {version}, not {GAME_VERSION}")
    runtime = jdk_runtime_version(jdk)
    if runtime.split(".")[0].split("+")[0] != JDK_FEATURE:
        raise SystemExit(f"JDK {runtime} is not JDK {JDK_FEATURE}")
    return [f"# input jdk {runtime}", f"# input server {server_jar.name} sha256:{sha256(server_jar)}"]


def recorded_manifest(output: Path) -> list[str] | None:
    if not output.is_file():
        return None
    return [line for line in output.read_text(encoding="utf-8").splitlines() if line.startswith("# input ")]


def trace(jdk: Path, server_jar: Path, libs: list[Path], work: Path) -> list[str]:
    """Build the agent, run the prelude under it, and return the completion order."""
    javac = str(jdk / "bin" / "javac")
    sources = work / "src"
    agent_classes = work / "agent"
    boot_classes = work / "boot"
    for folder in (sources, agent_classes, boot_classes):
        folder.mkdir()
    (sources / "InitEndAgent.java").write_text(AGENT_SOURCE, encoding="utf-8")
    (sources / "InitEnd.java").write_text(INIT_END_SOURCE, encoding="utf-8")
    (sources / "Boot.java").write_text(BOOT_SOURCE, encoding="utf-8")
    class_path = ":".join([*(str(lib) for lib in libs), str(server_jar)])
    subprocess.run([javac, "-d", str(agent_classes), str(sources / "InitEndAgent.java")], check=True)
    manifest = work / "manifest.txt"
    manifest.write_text("Premain-Class: InitEndAgent\n", encoding="utf-8")
    agent = work / "agent.jar"
    subprocess.run(
        [str(jdk / "bin" / "jar"), "cfm", str(agent), str(manifest), "-C", str(agent_classes), "."],
        check=True,
    )
    subprocess.run(
        [javac, "-cp", class_path, "-d", str(boot_classes),
         str(sources / "InitEnd.java"), str(sources / "Boot.java")],
        check=True,
    )
    listing = work / "done.txt"
    run = subprocess.run(
        [str(jdk / "bin" / "java"), f"-javaagent:{agent}", "-cp", f"{class_path}:{boot_classes}",
         "Boot", str(listing)],
        cwd=work,
        capture_output=True,
        text=True,
        timeout=900,
    )
    if run.returncode != 0:
        raise SystemExit(f"the bootstrap run failed ({run.returncode}):\n{run.stderr[-4000:]}")
    if "INITEND-TRANSFORM-FAILED" in run.stderr:
        failed = [line for line in run.stderr.splitlines() if "INITEND-TRANSFORM-FAILED" in line]
        raise SystemExit("the agent could not rewrite every game class:\n" + "\n".join(failed[:20]))
    names = listing.read_text(encoding="utf-8").splitlines()
    if len(set(names)) != len(names):
        raise SystemExit("a class finished initializing twice")
    return names


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--server-jar", type=Path, required=True)
    parser.add_argument("--libs", type=Path, required=True)
    parser.add_argument("--jdk", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--record", action="store_true", help="write a new input manifest")
    args = parser.parse_args()
    server_jar = args.server_jar.resolve()
    libs = sorted(path.resolve() for path in args.libs.rglob("*.jar"))
    manifest = input_manifest(server_jar, args.jdk)
    recorded = recorded_manifest(args.output)
    if recorded is not None and recorded != manifest and not args.record:
        print("inputs differ from the recorded manifest (pass --record to accept):", file=sys.stderr)
        for line in sorted(set(recorded) ^ set(manifest)):
            print(f"  {line}", file=sys.stderr)
        return 1
    with tempfile.TemporaryDirectory(prefix="clinit-order-") as folder:
        names = trace(args.jdk.resolve(), server_jar, libs, Path(folder))
    text = HEADER + "".join(f"{line}\n" for line in manifest) + "".join(f"{name}\n" for name in names)
    args.output.write_text(text, encoding="utf-8")
    print(f"{len(names)} classes written to {args.output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
