#!/usr/bin/env python3
"""Vendor the Java runtime into the native mod, which is one crate.

A Horizon native mod is one flat crate (docs/modding/src/how-to/native-mods/016-the-mods-crate.md):
the launcher stages a single crate and refuses path dependencies, so the bytecode runtime that
``mod/`` runs is copied into it instead of being linked. This tool is the one place that copy is
made, so the mod never drifts from ``crates/horizon-native-java``:

* it copies every ``.rs`` file of ``crates/horizon-native-java/src`` except ``main.rs`` (the
  command-line probe, which the mod does not use) into ``mod/src/runtime/``;
* each data file a vendored source embeds with ``include_str!("…")``/``include_bytes!("…")``
  (a generated table, a test oracle's JSON) is copied beside it byte for byte, so the vendored
  module still finds it. The path must be a string literal inside ``src``: anything else is an
  error, never a silently missing file;
* ``lib.rs`` becomes ``runtime/mod.rs``, the module the mod's ``src/lib.rs`` declares;
* each ``crate::`` path is rewritten to ``crate::runtime::``, because the runtime is no longer a
  crate root but a module of the mod's crate. Relative paths (``super::``, ``self::``) and the
  ``#[path]`` submodules of ``client_surface.rs`` need no change.

The vendored files are committed: a clean clone builds the mod without running this tool.

``--mod <folder>`` writes or checks another mod folder of the tree instead of ``mod/``. It exists for
``mod-horizon/`` (the build on the official Horizon's ``horizon-mod-api``), whose copy is not
committed: its CI job and a local build generate it first (docs/mod-horizon.md). The bytes are the
same in every mod, with one difference for a mod folder that holds ``horizon-mod.toml`` (the official
Horizon's package rules accept only ``.rs`` and ``.toml`` files under ``src/``,
docs/modding/src/how-to/native-mods/03-data-files.md there): each embedded data file of another kind
becomes ``<name>.rs`` holding its text as one raw string literal, and the vendored source's
``include_str!("<name>")`` becomes ``include!("<name>.rs")``, so the same bytes reach the same
constant. Without ``--mod`` the tool writes, checks and prints exactly as described here.

There is one check, ``--check``: it regenerates the copy in memory from
``crates/horizon-native-java/src`` **as it is now** and compares it byte for byte with the committed
``mod/src/runtime/``. Every file must match, none may be missing, and nothing else may sit in the
copy. That one comparison catches both ways the copy can go wrong:

* a hand edit to ``mod/src/runtime/`` (the regenerated bytes differ from the committed ones);
* a runtime change that was not re-vendored (likewise), including a changed embedded data file.

CI runs it on every pull request and every push (``.github/workflows/ci.yml``), and every commit that
touches the runtime re-vendors in the same commit, so the mod always carries the runtime's current
behaviour.

(The copy used to be pinned by a ``mod/vendor.lock`` of per-file SHA-256 hashes and a source commit.
It changed in nearly every runtime PR, so any two runtime PRs conflicted on it; and it guarded nothing
the regenerate-and-compare check above does not, so it is gone.)

    python3 tools/vendor.py          # write (or refresh) mod/src/runtime
    python3 tools/vendor.py --check  # fail unless mod/src/runtime is exactly what that writes
    python3 tools/vendor.py --mod mod-horizon          # the same for mod-horizon/src/runtime
    python3 tools/vendor.py --mod mod-horizon --check
"""

from __future__ import annotations

import argparse
import os
import re
import sys
from pathlib import Path, PurePosixPath

# The crate the runtime comes from, and the mod that carries a copy of it.
RUNTIME_SRC = Path("crates/horizon-native-java/src")
MOD = Path("mod")
VENDOR = MOD / "src" / "runtime"
# `main.rs` is the command-line probe: neither a module of the library nor anything the mod calls.
SKIP = {PurePosixPath("main.rs")}
# The crate-root path a vendored file's `crate::` becomes.
PREFIX = "crate::runtime::"
# The runtime keeps one item for every capability the probe, the corpus tools and the weaver use;
# a mod calls a handful. Its warnings are the crate's, not the mod's, so the vendored root module
# silences the two that the whole-crate copy necessarily raises.
ROOT_HEADER = "// @generated by tools/vendor.py from crates/horizon-native-java/src; do not edit.\n#![allow(dead_code, unused_imports)]\n\n"
# `include_str!("path")` / `include_bytes!("path")`, with the literal path captured; and any use
# of the two macros at all, so one whose argument is not a plain literal is refused, not skipped.
INCLUDE_LITERAL = re.compile(rb'\binclude_(?:str|bytes)!\(\s*"([^"\\]+)"\s*\)')
INCLUDE_ANY = re.compile(rb"\binclude_(?:str|bytes)!\(")
# The manifest of a mod built under the official Horizon's package rules, and the file kinds those
# rules accept under `src/`; any other embedded file is vendored as Rust there (see the docstring).
HORIZON_MANIFEST = "horizon-mod.toml"
PACKAGE_SOURCE_SUFFIXES = {".rs", ".toml"}


def repo_root() -> Path:
    return Path(__file__).resolve().parents[1]


def vendored_name(relative: PurePosixPath) -> PurePosixPath:
    """Where one source file goes in `mod/src/runtime/`."""
    return PurePosixPath("mod.rs") if relative == PurePosixPath("lib.rs") else relative


def included_files(src: Path, path: Path, original: bytes) -> list[PurePosixPath]:
    """The data files one source embeds, relative to `src`.

    `include_str!`/`include_bytes!` resolve their path against the including file's directory,
    which the vendored copy keeps, so each file is copied to the same relative place. A macro whose
    argument is not a plain string literal, or a path that leaves `src`, cannot be copied and stops
    the tool: the mod's build would otherwise fail on a file nobody vendored.
    """
    literal = INCLUDE_LITERAL.findall(original)
    if len(literal) != len(INCLUDE_ANY.findall(original)):
        raise SystemExit(f"{path}: include_str!/include_bytes! of a non-literal path cannot be vendored")
    out = []
    for raw in literal:
        target = (path.parent / raw.decode("utf-8")).resolve()
        try:
            relative = target.relative_to(src.resolve())
        except ValueError:
            raise SystemExit(f"{path}: includes {raw.decode()}, outside {RUNTIME_SRC}") from None
        if not target.is_file():
            raise SystemExit(f"{path}: includes {raw.decode()}, which does not exist")
        out.append(PurePosixPath(relative.as_posix()))
    return out


def vendored_files_on_disk(root: Path, vendor: Path = VENDOR) -> set[str]:
    """Every file under `mod/src/runtime/` (or `vendor`): sources and the data files they embed."""
    target = root / vendor
    if not target.is_dir():
        return set()
    return {path.relative_to(target).as_posix() for path in target.rglob("*") if path.is_file()}


def rust_data_name(relative: PurePosixPath) -> PurePosixPath:
    """Where an embedded data file goes as Rust: `<name>.rs` beside where it would be."""
    return relative.with_name(relative.name + ".rs")


def rust_data(relative: PurePosixPath, content: bytes) -> bytes:
    """One embedded text file as a Rust source file whose only expression is its raw string."""
    text = content.decode("utf-8")
    if "\r" in text:
        raise SystemExit(f"{RUNTIME_SRC / relative}: a raw string literal cannot keep a carriage return")
    hashes = "#" * (max((len(run) for run in re.findall(r'"(#*)', text)), default=0) + 1)
    header = f"// @generated by tools/vendor.py from {RUNTIME_SRC / relative}; do not edit.\n"
    return f'{header}r{hashes}"{text}"{hashes}\n'.encode("utf-8")


def as_rust_include(text: str, data: set[PurePosixPath], path: PurePosixPath) -> str:
    """`include_str!("<name>")` of a data file -> `include!("<name>.rs")`, in one vendored source."""

    def replace(match: re.Match[str]) -> str:
        name = match.group(2)
        included = PurePosixPath(os.path.normpath((path.parent / name).as_posix()))
        if included not in data:
            return match.group(0)
        if match.group(1) != "str":
            raise SystemExit(f"{RUNTIME_SRC / path}: include_bytes!({name!r}) cannot become Rust text")
        return f'include!("{name}.rs")'

    return re.sub(r'\binclude_(str|bytes)!\(\s*"([^"\\]+)"\s*\)', replace, text)


def expected(root: Path, rust_text: bool = False) -> dict[str, tuple[bytes, bytes]]:
    """Every file the vendoring produces: {destination path: (source bytes, vendored bytes)}.

    A data file a source embeds is vendored unchanged (source bytes == vendored bytes), or, with
    `rust_text` (a mod under the official Horizon's package rules), as `<name>.rs` when its kind
    is not one those rules accept.
    """
    src = root / RUNTIME_SRC
    files = {}
    data: set[PurePosixPath] = set()
    sources = []
    for path in sorted(src.rglob("*.rs")):
        relative = PurePosixPath(path.relative_to(src).as_posix())
        if relative in SKIP:
            continue
        original = path.read_bytes()
        data.update(included_files(src, path, original))
        sources.append((relative, original))
    as_rust = {name for name in data if rust_text and name.suffix not in PACKAGE_SOURCE_SUFFIXES}
    for relative, original in sources:
        # The runtime stops being a crate root: its own paths move under the mod's `runtime`
        # module. Token-level enough: `crate::` is a path qualifier in this tree and never
        # appears inside a string or a character literal (checked by the test that reads it).
        text = original.decode("utf-8").replace("crate::", PREFIX)
        if as_rust:
            text = as_rust_include(text, as_rust, relative)
        destination = vendored_name(relative)
        if destination == PurePosixPath("mod.rs"):
            text = ROOT_HEADER + text
        files[str(destination)] = (original, text.encode("utf-8"))
    for relative in sorted(data):
        if relative.suffix == ".rs":
            raise SystemExit(f"{RUNTIME_SRC / relative}: an included .rs file would be rewritten")
        content = (src / relative).read_bytes()
        if relative in as_rust:
            files[str(rust_data_name(relative))] = (content, rust_data(relative, content))
        else:
            files[str(relative)] = (content, content)
    return files


def drift(root: Path, vendor: Path = VENDOR, rust_text: bool = False) -> list[str]:
    """Every difference between the committed copy and what the runtime source vendors to now.

    Byte for byte, file by file: a hand edit to `mod/src/runtime/`, a runtime change nobody
    re-vendored, a vendored file whose source is gone and a missing copy all show up here.
    """
    problems = []
    files = expected(root, rust_text)
    target = root / vendor
    for name, (_, vendored_bytes) in sorted(files.items()):
        path = target / name
        source = RUNTIME_SRC / ("lib.rs" if name == "mod.rs" else name)
        if PurePosixPath(name.removesuffix(".rs")).suffix not in {"", ".rs"}:
            # A data file vendored as Rust (`<name>.rs`) comes from `<name>`.
            source = RUNTIME_SRC / name.removesuffix(".rs")
        if not path.is_file():
            problems.append(f"{vendor / name}: missing (vendored from {source})")
        elif path.read_bytes() != vendored_bytes:
            problems.append(
                f"{vendor / name}: differs from what {source} vendors to "
                "(edited by hand, or the runtime changed and was not re-vendored)"
            )
    for name in sorted(vendored_files_on_disk(root, vendor) - set(files)):
        problems.append(f"{vendor / name}: vendored file has no source in {RUNTIME_SRC}")
    return problems


def write(root: Path, vendor: Path = VENDOR, rust_text: bool = False) -> None:
    files = expected(root, rust_text)
    target = root / vendor
    target.mkdir(parents=True, exist_ok=True)
    for name, (_, vendored_bytes) in sorted(files.items()):
        destination = target / name
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_bytes(vendored_bytes)
    # A file whose source is gone (or that no source embeds any more) stops being part of the mod.
    for name in vendored_files_on_disk(root, vendor) - set(files):
        (target / name).unlink()


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail unless mod/src/runtime is exactly what the runtime source vendors to now",
    )
    parser.add_argument("--repo", type=Path, default=None, help="the tree to vendor (default: this one)")
    parser.add_argument(
        "--mod",
        type=Path,
        default=None,
        help="vendor into or check this mod folder of the tree instead of mod/ (e.g. mod-horizon); "
        "its copy is generated, never committed",
    )
    args = parser.parse_args(argv)
    root = (args.repo or repo_root()).resolve()
    vendor = VENDOR
    rust_text = False
    if args.mod is not None:
        # The write step deletes stale files under the folder's `src/runtime/`, so the folder must
        # be inside the tree once `..`, an absolute path and symbolic links are resolved.
        folder = (root / args.mod).resolve()
        if folder == root or not folder.is_relative_to(root):
            parser.error(f"--mod {args.mod}: not a folder inside {root}")
        if not folder.is_dir():
            parser.error(f"--mod {args.mod}: no such mod folder in {root}")
        vendor = folder.relative_to(root) / "src" / "runtime"
        rust_text = (folder / HORIZON_MANIFEST).is_file()
    if args.check:
        problems = drift(root, vendor, rust_text)
        for problem in problems:
            print(f"drift: {problem}", file=sys.stderr)
        if problems:
            hint = (
                "run python3 tools/vendor.py and commit mod/src/runtime"
                if args.mod is None
                else f"run python3 tools/vendor.py --mod {args.mod}"
            )
            print(
                f"{len(problems)} vendored file(s) are not what tools/vendor.py produces; {hint}",
                file=sys.stderr,
            )
            return 1
        where = "" if args.mod is None else f" in {vendor}"
        print(f"{len(expected(root, rust_text))} vendored file(s) match {RUNTIME_SRC}{where}")
        return 0
    write(root, vendor, rust_text)
    print(f"vendored {len(expected(root, rust_text))} file(s) into {vendor}")
    return 0

if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
