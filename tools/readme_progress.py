#!/usr/bin/env python3
"""Rewrite the README's "Progress at a glance" tables from one census run.

Run it after each merge batch, on the batch census's JSON (`census_compare.py --json`):

    python3 tools/readme_progress.py census.json --date 2026-11-17

It reads the merged side of the census (main after the batch) in `closure` mode, where each jar
runs beside its declared dependencies, the way a player installs it. It rewrites only the text
between the `progress:start` and `progress:end` markers in README.md, so the hand-written
"works now" and "next" lines around them stay as they are.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

START = "<!-- progress:start (generated by tools/readme_progress.py; do not edit by hand) -->"
END = "<!-- progress:end -->"

# The corpora in the order the table shows them, with a plain-words name.
CORPORA = [
    ("corpus-xl", "Wide Fabric set"),
    ("mega", "Mega Fabric set"),
    ("neoforge", "NeoForge 26.3 set"),
]
# The census roles that run client entrypoints; `library`, `client` and `*-noentry` rows are skipped
# jars and say nothing about whether a mod works.
CLIENT_ROLES = ("client-only", "dual-client", "neo-client")
VERDICTS = ("ran-clean", "ran-hollow", "ran-partial", "refused")


def _row(totals: list[dict]) -> dict[str, int]:
    """Sum the verdict counts and unknown calls of several census rows."""
    row = {key: 0 for key in (*VERDICTS, "unknown_total")}
    for entry in totals:
        for key in row:
            row[key] += int(entry.get(key, 0))
    return row


def _table(rows: list[tuple[str, dict[str, int]]]) -> list[str]:
    lines = [
        "| Mod set | Mods run | Ran clean | Ran on counted calls | Stopped partway | Refused | Unknown calls counted |",
        "|---|---:|---:|---:|---:|---:|---:|",
    ]
    for name, row in rows:
        run = sum(row[key] for key in VERDICTS)
        lines.append(
            f"| {name} | {run} | {row['ran-clean']} | {row['ran-hollow']} | {row['ran-partial']} "
            f"| {row['refused']} | {row['unknown_total']} |"
        )
    return lines


def render(census: dict, date: str) -> str:
    """The generated block, markers included."""
    roles = census["roles"]
    server = roles["server"]["merged"]["totals"]
    client = roles["client"]["merged"]["totals"]
    sha = str(roles["server"]["merged"].get("sha") or census.get("merged_sha", ""))
    server_rows = []
    client_rows = []
    for corpus, name in CORPORA:
        key = f"{corpus}/closure/server"
        if key not in server:
            raise ValueError(f"census has no {key} row")
        server_rows.append((name, _row([server[key]])))
        picked = [client[f"{corpus}/closure/{role}"] for role in CLIENT_ROLES if f"{corpus}/closure/{role}" in client]
        if not picked:
            raise ValueError(f"census has no closure client rows for {corpus}")
        client_rows.append((name, _row(picked)))
    lines = [
        START,
        f"Measured on {date} on commit `{sha[:10]}` (a merge batch; `main` after it has the same tree),",
        "with each mod beside its declared dependencies. Definitions: [docs/unmodelled-calls.md](docs/unmodelled-calls.md).",
        "",
        "**On a dedicated server** (each mod's server entrypoints):",
        "",
        *_table(server_rows),
        "",
        "**On a client** (client entrypoints, and mods with both):",
        "",
        *_table(client_rows),
        "",
        "- **Ran clean**: every entrypoint finished, and every call got Java's exact answer.",
        "- **Ran on counted calls**: every entrypoint finished, but some calls reached something Decaf doesn't",
        "  model yet. Those are counted, never guessed, so the mod may not do everything it would in Java.",
        "- **Stopped partway**: some entrypoints ran and at least one failed (a real loader would have thrown).",
        "- **Refused**: nothing ran: bad metadata, no entrypoint found, or an exception before anything",
        "  finished. The common one now is a `NullPointerException` on a counted call's empty answer.",
        "- **Unknown calls counted**: every call Decaf answered \"I don't know\" instead of guessing. It goes",
        "  up when a refused mod starts running and reaches calls nobody has modelled yet.",
        END,
    ]
    return "\n".join(lines)


def rewrite(readme: str, block: str) -> str:
    start = readme.find(START)
    end = readme.find(END)
    if start < 0 or end < start:
        raise ValueError("README.md has no progress:start/progress:end block")
    return readme[:start] + block + readme[end + len(END):]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("census", type=Path, help="census_compare.py --json output")
    parser.add_argument("--date", required=True, help="the day the census ran, YYYY-MM-DD")
    parser.add_argument("--readme", type=Path, default=Path(__file__).resolve().parent.parent / "README.md")
    args = parser.parse_args(argv)
    try:
        block = render(json.loads(args.census.read_text()), args.date)
        args.readme.write_text(rewrite(args.readme.read_text(), block))
    except (ValueError, KeyError) as error:
        print(f"readme_progress: {error}", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
