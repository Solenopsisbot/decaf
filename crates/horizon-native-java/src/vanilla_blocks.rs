//! The block constants of 26.3's `net.minecraft.world.level.block.Blocks`, and
//! the id each registers (#239's review B2).
//!
//! Generated from the 26.3 server jar's bytecode (`javap -c` of `Blocks.<clinit>`:
//! each `putstatic Blocks.<FIELD>` follows a `getstatic` of the
//! `references.BlockIds`/`BlockItemIds` constant whose `<clinit>` holds the id).
//! Only names are kept, no code. Of the 878 constants, every id is its field's
//! name in lower case except the two in [`field_id`]. A field this list lacks
//! (`Blocks.CHAIN`, removed before 26.3) is no 26.3 block: Java fails to link it
//! (`NoSuchFieldError`), so the host answers no block for it.

/// The block id `Blocks.<field>` registers (`minecraft:stone`), `None` for a
/// field 26.3's `Blocks` does not have.
pub(crate) fn field_id(field: &str) -> Option<String> {
    FIELDS.binary_search(&field).ok()?;
    let path = match field {
        "POTTED_AZALEA" => "potted_azalea_bush".to_owned(),
        "POTTED_FLOWERING_AZALEA" => "potted_flowering_azalea_bush".to_owned(),
        _ => field.to_ascii_lowercase(),
    };
    Some(format!("minecraft:{path}"))
}

pub(crate) fn handle(id: &str) -> Option<crate::Value> {
    FIELDS
        .iter()
        .any(|field| field_id(field).as_deref() == Some(id))
        .then(|| crate::game_object::server_value(format!("game/block/{id}")))
}

